def _box(x, y, w, h, title, rows, col='#4f46e5', fill='#ffffff'):
    o = ['<rect x="%d" y="%d" width="%d" height="%d" rx="10" fill="%s" stroke="%s" stroke-width="1.5"/>'
         % (x, y, w, h, fill, col)]
    o.append('<text x="%d" y="%d" font-size="11.5" font-weight="700" fill="%s">%s</text>'
             % (x + 14, y + 22, col, title))
    for i, r in enumerate(rows):
        o.append('<text x="%d" y="%d" font-size="11" fill="#4b5563">%s</text>'
                 % (x + 14, y + 44 + i * 22, r))
    return o


